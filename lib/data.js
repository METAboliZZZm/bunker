// Колоды игры «Бункер».
//
// Формат строки:  очки теги | текст
//   очки  — от -3 до 3, насколько карта помогает выжить. По ним раздача уравнивает игроков.
//   теги  — med (медицина), food (еда), tech (техника), def (защита), surv (выживание снаружи),
//           psy (психология), know (знания), fun (моральный дух).
//           M / F — карта только для мужчин / женщин, nofert — не может иметь детей, preg — беременность.
//           anti-med, anti-tech… — карта мешает профессии с таким тегом (хирург, который боится крови).
//   nostaj — без стажа в профессии.
//   {он|она} — форма слова для мужчины и для женщины: «Смел{ый|ая}».
// Строки, которые начинаются с //, игнорируются.

function deck(src) {
  return src.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('//')).map((l) => {
    const i = l.indexOf('|');
    const head = l.slice(0, i).trim().split(/\s+/);
    return { v: Number(head[0]), tags: head.slice(1), t: l.slice(i + 1).trim() };
  });
}

